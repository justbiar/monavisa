// Writes src/abis.ts from Foundry build output. Run `forge build` in contracts/ first.
// With --check, exits non-zero when src/abis.ts is out of date instead of writing it.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const CONTRACTS = ["PlanFactory", "SubscriptionRegistry", "AutopayModule", "FeeCollector"];

const out = new URL("../../../contracts/out/", import.meta.url);
const target = fileURLToPath(new URL("../src/abis.ts", import.meta.url));

const lowerFirst = (name) => name[0].toLowerCase() + name.slice(1);

let source = "// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit.\n";
for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(new URL(`${name}.sol/${name}.json`, out), "utf8"));
  source += `\nexport const ${lowerFirst(name)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
}

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== source) {
    console.error("packages/core/src/abis.ts is out of date. Run `pnpm abis`.");
    process.exit(1);
  }
  console.log("abis.ts is up to date");
} else {
  writeFileSync(target, source);
  console.log(`Wrote ${CONTRACTS.length} ABIs to ${target}`);
}
